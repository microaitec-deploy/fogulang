/** A guide program (examples/guides/<name>.fg) with the output it really printed. */
const Program: React.FC<{ name: string; onRun: (code: string) => void }> = ({ name, onRun }) => {
  const g = GUIDES[name];
  if (!g) return null;
  return (
    <>
      <DocCodeBlock title={`examples/guides/${name}.fg`} code={g.code} onRun={onRun} />
      <DocCodeBlock lang="text" title="output" code={g.output} />
    </>
  );
};

