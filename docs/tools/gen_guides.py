#!/usr/bin/env python3
"""Runs the guide programs (examples/guides/*.fg) and writes their code and real
output to docs/view/src/data/guides.generated.ts, used by the Guides pages.

    python docs/tools/gen_guides.py           # run them all and write the file
    python docs/tools/gen_guides.py --check   # only run them (fails on any error)

Each program runs in an empty temporary folder with target/release/fogu (or
$FOGU_BIN), so files it creates do not land in the repository.
"""
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
GUIDES = ROOT / "examples" / "guides"
OUT = ROOT / "docs" / "view" / "src" / "data" / "guides.generated.ts"


def binary():
    env = os.environ.get("FOGU_BIN")
    if env:
        return pathlib.Path(env)
    for p in [ROOT / "target" / "release" / "fogu", ROOT / "target" / "release" / "fogu.exe"]:
        if p.exists():
            return p
    return pathlib.Path(shutil.which("fogu") or "fogu")


def run(fogu, src):
    with tempfile.TemporaryDirectory(prefix="fogu-guide-") as tmp:
        target = pathlib.Path(tmp) / src.name
        shutil.copy(src, target)
        env = dict(os.environ, NO_COLOR="1")
        r = subprocess.run([str(fogu), "run", src.name], cwd=tmp, capture_output=True, text=True, timeout=120, env=env)
        return r.returncode, r.stdout, r.stderr


def main():
    check = "--check" in sys.argv
    fogu = binary()
    data, failed = {}, 0
    for src in sorted(GUIDES.glob("*.fg")):
        code, out, err = run(fogu, src)
        if code != 0:
            failed += 1
            print(f"FAIL {src.name}\n{out}{err}")
            continue
        print(f"  ok  {src.name}")
        data[src.stem] = {"code": src.read_text(encoding="utf-8").replace("\r\n", "\n"), "output": out.rstrip("\n")}
    if failed:
        print(f"{failed} guide(s) failed")
        sys.exit(1)
    if not check:
        text = "// Generated by docs/tools/gen_guides.py from examples/guides/*.fg — do not edit.\n"
        text += "export const GUIDES: Record<string, { code: string; output: string }> = "
        text += json.dumps(data, indent=2, ensure_ascii=False) + ";\n"
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {len(data)} guides to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
